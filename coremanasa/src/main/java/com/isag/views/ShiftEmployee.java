package com.isag.views;

/**
 *
 * @author IT Shop
 */
public class ShiftEmployee {

    private String employeeCode;
    private String shiftCode;
    private String remCompanyCode;

    /**
     * @return the employeeCode
     */
    public String getEmployeeCode() {
        return employeeCode;
    }

    /**
     * @param employeeCode the employeeCode to set
     */
    public void setEmployeeCode(String employeeCode) {
        this.employeeCode = employeeCode;
    }

    /**
     * @return the shiftCode
     */
    public String getShiftCode() {
        return shiftCode;
    }

    /**
     * @param shiftCode the shiftCode to set
     */
    public void setShiftCode(String shiftCode) {
        this.shiftCode = shiftCode;
    }

    /**
     * @return the remCompanyCode
     */
    public String getRemCompanyCode() {
        return remCompanyCode;
    }

    /**
     * @param remCompanyCode the remCompanyCode to set
     */
    public void setRemCompanyCode(String remCompanyCode) {
        this.remCompanyCode = remCompanyCode;
    }
}
